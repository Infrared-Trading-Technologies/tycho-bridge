//! Build script for tycho-ffi.
//!
//! This generates the C header file using cbindgen.

fn main() {
    // Only regenerate header when source files change
    println!("cargo:rerun-if-changed=src/");
    println!("cargo:rerun-if-changed=cbindgen.toml");

    // Get paths
    let crate_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let workspace_dir = std::path::Path::new(&crate_dir)
        .parent()
        .and_then(|p| p.parent())
        .expect("Could not find workspace root");

    let header_path = workspace_dir.join("include").join("tycho_bridge.h");

    // Ensure include directory exists
    std::fs::create_dir_all(workspace_dir.join("include"))
        .expect("Could not create include directory");

    // Generate header using cbindgen
    let config_path = std::path::Path::new(&crate_dir).join("cbindgen.toml");

    // Load and modify config to ensure C language
    let mut config = match cbindgen::Config::from_file(&config_path) {
        Ok(c) => {
            println!("cargo:warning=Loaded config from {}", config_path.display());
            c
        }
        Err(e) => {
            eprintln!("Warning: Could not load cbindgen.toml: {}", e);
            eprintln!("Using default configuration");
            cbindgen::Config::default()
        }
    };

    // Force C language and set header
    config.language = cbindgen::Language::C;
    config.cpp_compat = false;
    config.no_includes = true;
    config.include_guard = None;
    config.header = Some(
        r#"/* Auto-generated by cbindgen. Do not edit manually. */
/* This file provides C bindings for the Tycho Bridge library. */
#ifndef TYCHO_BRIDGE_H
#define TYCHO_BRIDGE_H

#include <stdarg.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
"#
        .to_string(),
    );
    config.trailer = Some("#endif /* TYCHO_BRIDGE_H */".to_string());

    match cbindgen::Builder::new()
        .with_crate(&crate_dir)
        .with_config(config)
        .generate()
    {
        Ok(bindings) => {
            bindings.write_to_file(&header_path);
            println!(
                "cargo:warning=Generated C header: {}",
                header_path.display()
            );
        }
        Err(e) => {
            eprintln!("Warning: Could not generate C bindings: {}", e);
            // Don't fail the build if cbindgen fails - the library can still be used
            // from Rust or with manually-written headers
        }
    }
}
